"""Validate the user's explicitly registered build-tool checkout paths."""
import json
import os
from pathlib import Path
import shlex
import tomllib
from .contracts import BuildError


TOOL_NAMES = frozenset({"BUILDFLOW_PATH", "FNPACKKIT_PATH"})


def config_directory() -> Path:
    """Use XDG_CONFIG_HOME or the user's .config directory on either host."""
    configured = os.environ.get("XDG_CONFIG_HOME")
    path = Path(configured).expanduser() if configured else Path.home() / ".config"
    if not path.is_absolute():
        raise BuildError("XDG_CONFIG_HOME 必须是绝对路径")
    return path / "buildflow"


def checked_tool(name: str, value: str | Path) -> Path:
    """Reject empty overrides and paths that are not the named checkout."""
    if name not in TOOL_NAMES:
        raise BuildError(f"不支持的工具变量: {name}")
    text = os.fspath(value)
    if not text or any(char in text for char in "\n\r\0"):
        raise BuildError(f"{name} 必须是有效工具路径，不能是空值或包含换行")
    path = Path(text).expanduser()
    if not path.is_absolute():
        raise BuildError(f"{name} 必须是绝对路径: {path}")
    path = path.resolve()
    package = name.removesuffix("_PATH").lower()
    try:
        metadata = tomllib.loads((path / "pyproject.toml").read_text(encoding="utf-8"))
        if metadata.get("project", {}).get("name", "").lower() != package:
            raise ValueError(f"project.name 必须为 {package}")
        if not (path / "src" / package / "__init__.py").is_file():
            raise ValueError(f"缺少 src/{package}/__init__.py")
    except (OSError, ValueError, AttributeError) as exc:
        raise BuildError(f"{name} 工具路径无效 {path}: {exc}") from exc
    return path


def read_tools(directory: Path | None = None) -> dict[str, str]:
    """Read schema 1 tool locations without executing the generated shell."""
    path = (directory or config_directory()) / "environment.json"
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict) or type(data.get("schema")) is not int or data["schema"] != 1:
            raise ValueError("schema 必须是整数 1")
        tools = data.get("tools")
        if not isinstance(tools, dict) or set(tools) - TOOL_NAMES:
            raise ValueError("tools 只允许 BUILDFLOW_PATH 和 FNPACKKIT_PATH")
        for name, value in tools.items():
            if not isinstance(value, str) or not value or not Path(value).is_absolute():
                raise ValueError(f"{name} 必须是非空绝对路径")
            if any(char in value for char in "\n\r\0"):
                raise ValueError(f"{name} 路径包含控制字符")
        return tools
    except (OSError, ValueError) as exc:
        raise BuildError(f"无法读取工具环境 {path}: {exc}") from exc


def resolve_tool(name: str) -> Path | None:
    """Resolve an explicit environment override before the user registration."""
    if name not in TOOL_NAMES:
        raise BuildError(f"不支持的工具变量: {name}")
    if name in os.environ:
        return checked_tool(name, os.environ[name])
    value = read_tools().get(name)
    return checked_tool(name, value) if value is not None else None


def shell_environment(tools: dict[str, str]) -> str:
    """Generate quoted defaults without overriding any explicit environment."""
    lines = ["# Generated by BuildFlow setup; update paths by running setup again."]
    for name, value in sorted(tools.items()):
        lines.extend([f'if [ "${{{name}+x}}" != x ]; then',
                      f"    export {name}={shlex.quote(value)}", "fi"])
    return "\n".join(lines) + "\n"
